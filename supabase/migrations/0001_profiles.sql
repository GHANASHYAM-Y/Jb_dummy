-- ── 2. profiles table ──────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.profiles (
  -- Primary key: same UUID as the auth.users row.
  id              UUID        PRIMARY KEY
                              REFERENCES auth.users(id) ON DELETE CASCADE,

  -- Public-facing identifier: EVO- followed by 6 uppercase alphanumeric chars.
  -- Generated by the trigger; never editable by the user.
  evoora_id       TEXT        NOT NULL UNIQUE,

  -- Display name chosen during signup (editable).
  display_name    TEXT        NOT NULL
                              CONSTRAINT display_name_length
                                CHECK (char_length(display_name) BETWEEN 2 AND 64),

  -- Optional avatar stored in Supabase Storage (editable).
  avatar_url      TEXT        NULL,

  -- Optional short bio (editable).
  bio             TEXT        NULL
                              CONSTRAINT bio_length
                                CHECK (bio IS NULL OR char_length(bio) <= 280),

  -- Preferred UI language (editable).
  preferred_locale public.locale NOT NULL DEFAULT 'en',

  -- Soft public/private toggle (editable).
  is_public       BOOLEAN     NOT NULL DEFAULT TRUE,

  -- Timestamps (managed by the database, not client).
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Ensure evoora_id is NEVER null (belt-and-suspenders beyond NOT NULL).
ALTER TABLE public.profiles
  ALTER COLUMN evoora_id SET NOT NULL;

-- ── 3. Indexes ─────────────────────────────────────────────────────────────────

-- evoora_id uniqueness index (the UNIQUE constraint above creates one, but
-- name it explicitly for clarity in monitoring/explain).
CREATE UNIQUE INDEX IF NOT EXISTS profiles_evoora_id_idx
  ON public.profiles (evoora_id);

-- Case-insensitive display_name search for future friend-search features.
CREATE INDEX IF NOT EXISTS profiles_display_name_lower_idx
  ON public.profiles (lower(display_name));

-- ── 4. updated_at trigger ──────────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS profiles_set_updated_at ON public.profiles;
CREATE TRIGGER profiles_set_updated_at
  BEFORE UPDATE ON public.profiles
  FOR EACH ROW
  EXECUTE FUNCTION public.set_updated_at();

-- ── 5. Evoora ID generator ──────────────────────────────────────────────────────
--
-- Generates a unique ID of the form EVO-XXXXXX where X is an uppercase
-- alphanumeric character.  Uses a bounded retry loop (max 10 attempts) to
-- handle the astronomically unlikely case of a collision.
--
-- Character set: 0-9, A-Z (36 chars).  Space = 36^6 ≈ 2.18 billion IDs.
-- We reject any IDs that start with a digit to avoid numeric confusion.
-- Actual entropy ≈ 26 × 36^5 ≈ 1.35 billion distinct IDs.
--
-- SECURITY DEFINER so the function can read the profiles table to check
-- uniqueness without relying on the caller's RLS context.

CREATE OR REPLACE FUNCTION public.generate_evoora_id()
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions
AS $$
#variable_conflict use_variable
DECLARE
  chars  TEXT    := 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';
  id     TEXT;
  i      INTEGER;
  attempt INTEGER := 0;
BEGIN
  LOOP
    attempt := attempt + 1;
    IF attempt > 10 THEN
      RAISE EXCEPTION 'Failed to generate a unique Evoora ID after 10 attempts';
    END IF;

    -- Build a 6-character random string from the charset.
    id := '';
    FOR i IN 1..6 LOOP
      id := id || substr(chars,
                         (get_byte(gen_random_bytes(1), 0) % length(chars)) + 1,
                         1);
    END LOOP;

    -- Require the first character to be a letter (not a digit).
    CONTINUE WHEN substr(id, 1, 1) ~ '^[0-9]$';

    -- Prefix and uniqueness check.
    id := 'EVO-' || id;
    EXIT WHEN NOT EXISTS (
      SELECT 1 FROM public.profiles p WHERE p.evoora_id = generate_evoora_id.id
    );
  END LOOP;

  RETURN id;
END;
$$;

-- ── 6. New-user profile creation trigger ───────────────────────────────────────
--
-- Fires AFTER INSERT on auth.users.  Creates one profile row per new user,
-- pulling display_name from user_metadata if the client supplied it during
-- signUp({ data: { display_name: '...' } }).
--
-- ON CONFLICT DO NOTHING makes this idempotent — repeated callbacks or
-- duplicate triggers cannot create duplicate profiles.

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions
AS $$
DECLARE
  raw_name TEXT;
  clean_name TEXT;
BEGIN
  -- Pull the display_name passed via signUp options.data (may be null).
  raw_name := NEW.raw_user_meta_data ->> 'display_name';

  -- Fall back to the portion of the email address before the @.
  IF raw_name IS NULL OR trim(raw_name) = '' THEN
    raw_name := split_part(NEW.email, '@', 1);
  END IF;

  -- Enforce the 2–64 char constraint: truncate if necessary.
  clean_name := left(trim(raw_name), 64);
  IF char_length(clean_name) < 2 THEN
    clean_name := left(clean_name || '00', 2);
  END IF;

  INSERT INTO public.profiles (
    id,
    evoora_id,
    display_name,
    preferred_locale,
    is_public
  )
  VALUES (
    NEW.id,
    public.generate_evoora_id(),
    clean_name,
    'en',
    TRUE
  )
  ON CONFLICT (id) DO NOTHING;

  RETURN NEW;
END;
$$;

-- Idempotent trigger creation.
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW
  EXECUTE FUNCTION public.handle_new_user();

-- ── 7. Row Level Security ──────────────────────────────────────────────────────

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

-- Anyone (including anonymous visitors) can read public profiles.
-- Private profiles are only readable by the owner.
DROP POLICY IF EXISTS "profiles_select" ON public.profiles;
CREATE POLICY "profiles_select"
  ON public.profiles
  FOR SELECT
  USING (
    is_public = TRUE
    OR auth.uid() = id
  );

-- Users can only update their own profile row.
DROP POLICY IF EXISTS "profiles_update" ON public.profiles;
CREATE POLICY "profiles_update"
  ON public.profiles
  FOR UPDATE
  USING (auth.uid() = id)
  WITH CHECK (
    auth.uid() = id
    -- Prevent client from changing protected columns.
    -- (evoora_id and id cannot be set because they are excluded from the
    --  update policy; the DB constraint enforces uniqueness regardless.)
  );

-- No INSERT from client — profiles are created by the trigger only.
DROP POLICY IF EXISTS "profiles_insert" ON public.profiles;
CREATE POLICY "profiles_insert"
  ON public.profiles
  FOR INSERT
  WITH CHECK (FALSE);  -- deny all client inserts; trigger uses SECURITY DEFINER

-- No DELETE from client — account deletion uses a server-side API route
-- with the service role key.
DROP POLICY IF EXISTS "profiles_delete" ON public.profiles;
CREATE POLICY "profiles_delete"
  ON public.profiles
  FOR DELETE
  USING (FALSE);

-- ── 8. Column-level protection via updatable view (optional enhancement) ───────
--
-- The UPDATE policy above allows updating any column of the user's own row.
-- To prevent a crafted API call from changing evoora_id, we create a
-- security barrier view that exposes only the editable subset.
-- Application code should always target this view for user-initiated updates.

CREATE OR REPLACE VIEW public.profiles_editable
  WITH (security_barrier = TRUE, security_invoker = TRUE)
AS
  SELECT
    id,
    evoora_id,          -- read-only in the view; omit from UPDATE targets
    display_name,
    avatar_url,
    bio,
    preferred_locale,
    is_public,
    created_at,
    updated_at
  FROM public.profiles
  WHERE auth.uid() = id;   -- callers only see their own row

-- Grant the anon and authenticated roles the minimum they need.
GRANT SELECT ON public.profiles TO anon, authenticated;
GRANT UPDATE (display_name, avatar_url, bio, preferred_locale, is_public)
  ON public.profiles TO authenticated;
GRANT SELECT ON public.profiles_editable TO authenticated;

-- ── 9. Protect the generator and trigger functions ─────────────────────────────
-- Revoke direct execution from the public / anon roles.
-- Only the trigger (SECURITY DEFINER) calls these internally.
REVOKE EXECUTE ON FUNCTION public.generate_evoora_id() FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION public.handle_new_user()    FROM PUBLIC;

